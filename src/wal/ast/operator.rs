//! Operator enum for WAL
//!
//! All 76 operators supported by WAL language.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Operator {
    // Waveform operations
    Load,
    Unload,
    Step,
    EvalFile,
    LoadedTraces,
    IsSignal,
    Signals,
    Index,
    MaxIndex,
    Ts,
    TraceName,
    TraceFile,

    // Math operations
    Add,
    Sub,
    Mul,
    Div,
    /// 整数除法(向零取整): `(div 10 3)` = 3(内测反馈: 硬件语境常要整除)
    DivInt,
    Exp,
    Floor,
    Ceil,
    Round,
    Abs,
    Mod,

    // Bitwise operations
    Bor,
    Band,
    Bxor,

    // Logical operations
    Not,
    Eq,
    Neq,
    Larger,
    Smaller,
    LargerEqual,
    SmallerEqual,
    And,
    Or,

    // Control flow
    Print,
    Printf,
    Define,
    Let,
    If,
    Case,
    When,
    Unless,
    Cond,
    While,
    Do,
    Alias,
    Unalias,
    Exit,
    Fn,
    Defmacro,
    Macroexpand,
    Gensym,
    Type,

    // Special forms
    Quote,
    Quasiquote,
    Unquote,
    Eval,
    RelEval,
    Slice,
    Get,

    // List operations
    List,
    First,
    Second,
    Last,
    Rest,
    In,
    Map,
    Max,
    Min,
    Fold,
    Length,
    Average,
    Zip,
    Sum,
    Third,
    Range,

    // Type checks
    IsDefined,
    IsAtom,
    IsSymbol,
    IsString,
    IsInt,
    IsList,
    IsBool,
    ForList,
    IsNull,
    Take,
    ConvertBinary,
    StringToInt,
    BitsToSint,
    StringToSymbol,
    SymbolToString,
    IntToString,

    // Signal operations
    Help,
    Find,
    FindG,
    Whenever,
    SignalWidth,
    SampleAt,
    /// (initial "sig") → $dumpvars 快照(t0 写入的原值; 没有初值条目则为 x)
    Initial,
    Count,
    Timeframe,
    Rising,
    Falling,
    IsX,
    IsZ,
    Changes,

    // Waveform time queries (time-aware, unlike index-based find/count)
    GetWave,
    Wave,
    At,
    CountRise,
    CountFall,
    CountEdges,
    Edges,
    FindSig,
    Search,
    Period,
    Freq,
    Doc,
    Beat,

    // Scope/group operations
    Allscopes,
    Scoped,
    ResolveScope,
    Setscope,
    UnsetScope,
    Groups,
    InGroup,
    InGroups,
    InScope,
    InScopes,
    ResolveGroup,

    // Array operations
    Array,
    Seta,
    Geta,
    GetaDefault,
    Dela,
    Mapa,

    // Virtual signal operations
    Defsig,

    StringAppend,

    // 指标与统计 (docs/waveform-metrics.md)
    Median,
    Percentile,
    Stddev,
    Stats,
    Histogram,
    Latency,
    Ipc,
}

